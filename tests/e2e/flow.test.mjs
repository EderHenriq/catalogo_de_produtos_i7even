// Roteiro completo, no iPhone (toque), contra o schema.sql real:
// variações → fotos → entrada em US$ com IMEI → seminovo com bateria →
// pedido escolhendo o IMEI → encomenda → PDF → WhatsApp → catálogo aberto →
// cliente pede pelo catálogo → loja transforma em pedido.
import { createDb, open, SHOTS, makePng, audit } from './harness.mjs';

const DEVICE = process.argv[2] || 'iPhone 13';
const tag = DEVICE.replace(/\W/g, '');
let fails = 0;
const ok = (c, m) => { console.log(`${c ? '  ✓' : '  ✗'} ${m}`); if (!c) fails++; };
const env = await createDb();
const q = async (sql, p) => (await env.db.query(sql, p)).rows;
const one = async (sql, p) => (await q(sql, p))[0];

const { browser, page, errors } = await open(env, { device: DEVICE });
const touch = DEVICE !== 'Desktop';
const tap = (loc) => (touch ? loc.first().tap() : loc.first().click());
const top = () => page.locator('dialog.modal[open]').last();
const shot = (n) => page.screenshot({ path: `${SHOTS}flow-${tag}-${n}.png` });
const auditNow = async (label) => { const i = await audit(page, label, { mobile: touch }); if (i.length) console.log('    ⚠', i.join('\n    ⚠ ')); };
const waitDb = async (sql, test, ms = 6000) => {
  const t0 = Date.now();
  for (;;) { const r = await q(sql); if (test(r)) return r; if (Date.now() - t0 > ms) return r; await page.waitForTimeout(150); }
};

await page.waitForSelector('.app');
const P16 = await one(`select id, colors from public.products where slug = 'iphone-16-pro'`);
const [C0, C1] = P16.colors;

console.log('1. variações (gerador): 2 capacidades × 2 cores × lacrado/seminovo');
await page.evaluate(() => { location.hash = '#/produtos'; });
await page.locator('[data-search]').fill('iphone 16 pro');
await page.waitForTimeout(300);
await tap(page.locator('.m-row', { has: page.locator('.m-title', { hasText: /^iPhone 16 Pro$/ }) }));
await page.waitForSelector('.product-hero');
await tap(top().locator('.modal-foot [data-add-variants]'));
await page.waitForSelector('[data-gen]');
const gen = top();
await tap(gen.locator('[data-pick="storages"][data-value="256GB"]'));
await tap(gen.locator('[data-pick="storages"][data-value="512GB"]'));
await tap(gen.locator(`[data-pick="colors"][data-value="${C0}"]`));
await tap(gen.locator(`[data-pick="colors"][data-value="${C1}"]`));
await tap(gen.locator('[data-pick="conditions"][data-value="Seminovo"]'));
await gen.locator('#vg-price').fill('799900');
await shot('01-gerador');
await auditNow('gerador');
await tap(gen.locator('[data-ok]'));
let r = await waitDb(`select count(*)::int n from public.product_variants where product_id = '${P16.id}'`, (x) => x[0].n === 8);
ok(r[0].n === 8, `8 variações criadas (${r[0].n})`);
r = await one(`select count(*)::int n from public.product_variants where product_id = '${P16.id}' and price = 7999`);
ok(r.n === 8, 'todas com o preço digitado (R$ 7.999,00)');
await page.waitForTimeout(300);
ok(await top().locator('.variant-row').count() === 8, 'ficha do modelo lista as 8');
await shot('02-ficha-modelo');

console.log('2. fotos: duas de uma vez, a primeira vira capa');
await tap(top().locator('.modal-foot [data-edit]'));
await page.waitForSelector('.gallery-field');
const files = [await makePng(page, { label: 'capa' }), await makePng(page, { label: 'verso', color: '#7a4b2a', w: 1400, h: 900 })];
await top().locator('input[data-file][multiple]').setInputFiles(files);
await page.waitForFunction(() => document.querySelectorAll('dialog[open] .gallery-tile img').length === 2, null, { timeout: 15000 });
await shot('03-fotos');
await auditNow('cadastro-modelo');
await tap(top().locator('.modal-foot [data-ok]'));
r = await waitDb(`select image_url, gallery from public.products where id = '${P16.id}'`, (x) => !!x[0].image_url);
ok(!!r[0].image_url && r[0].gallery.length === 1, 'capa + 1 foto na galeria gravadas');
ok([...env.uploads.keys()].filter((k) => k.includes('.t.')).length === 2, 'miniaturas de 720 px geradas para cada foto (grade do catálogo)');
const img = env.uploads.get(r[0].image_url.split('/produtos/')[1]);
ok(img && img.body.length < 250000, `foto reduzida no aparelho (${Math.round((img?.body.length || 0) / 1024)} KB, ${img?.type})`);
await page.keyboard.press('Escape');
await page.waitForTimeout(200);
while (await page.locator('dialog.modal[open]').count()) { await page.keyboard.press('Escape'); await page.waitForTimeout(150); }

