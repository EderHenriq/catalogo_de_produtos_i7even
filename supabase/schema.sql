-- ------------------------------------------------------------------ view --
-- Um registro por item vendido — facilita relatório "qual modelo mais sai".

create or replace view public.order_items_view
with (security_invoker = true) as
select
  o.id            as order_id,
  o.user_id,
  o.code,
  o.status,
  o.order_date,
  o.customer_name,
  item->>'categoryId'  as category_id,
  item->>'productId'   as product_id,
  item->>'productName' as product_name,
  item->>'variant'     as variant,
  item->>'color'       as color,
  item->>'condition'   as condition,
  coalesce((item->>'qty')::numeric, 1)        as qty,
  coalesce((item->>'unitPrice')::numeric, 0)  as unit_price,
  coalesce((item->>'unitCost')::numeric, 0)   as unit_cost,
  coalesce((item->>'unitPrice')::numeric, 0) * coalesce((item->>'qty')::numeric, 1) as line_total
from public.orders o
cross join lateral jsonb_array_elements(o.items) as item;

grant select on public.order_items_view to authenticated;

-- Um registro por pagamento recebido — responde "quanto entrou no caixa no mês",
-- que é diferente de "quanto foi faturado no mês" quando há parcelamento.

create or replace view public.order_payments_view
with (security_invoker = true) as
select
  o.id            as order_id,
  o.user_id,
  o.code,
  o.customer_name,
  o.status,
  o.total         as total_do_pedido,
  p->>'id'                                  as payment_id,
  nullif(p->>'date', '')::date              as recebido_em,
  coalesce((p->>'amount')::numeric, 0)      as valor,
  p->>'method'                              as forma,
  p->>'note'                                as observacao
from public.orders o
cross join lateral jsonb_array_elements(o.payments) as p;

grant select on public.order_payments_view to authenticated;

